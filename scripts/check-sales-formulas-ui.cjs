// Mutating acceptance test: run ONLY against the isolated QA database on port 18081.
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  globalThis.qaPage = page;
  const errors = [];
  let inputUrl = '';
  page.on('pageerror', e => { errors.push(e.message); console.log('PAGE ERROR', e.message); });
  page.on('request', r => { if (r.method() === 'GET' && r.url().includes('/sales-formulas/inputs?')) inputUrl = r.url(); });
  await page.goto('http://127.0.0.1:18081/');
  await page.getByLabel('账号', { exact: true }).fill('admin');
  await page.getByLabel('密码', { exact: true }).fill('Demo2026!');
  await page.getByRole('button', { name: /登录工作台/ }).click();
  const sales = page.locator('.commission-data-card').first();
  const market = page.locator('.commission-data-card').nth(1);
  await sales.getByRole('button', { name: '奖金公式', exact: true }).waitFor();
  if (await sales.locator('col').count() !== 19 || await market.locator('.formula-gear').count() !== 0) throw Error('columns or market scope changed');
  await sales.getByRole('button', { name: '奖金公式', exact: true }).click();
  await page.getByRole('dialog').getByText('涉及变量及来源').waitFor();
  await page.getByRole('dialog').screenshot({ path: 'docs/sales-formula-dialog.png' });
  await page.getByRole('button', { name: '查看 / 配置变量', exact: true }).click();
  const drawer = page.locator('.ant-drawer-body');
  await drawer.getByLabel('W 当季度目标（元）').waitFor();
  await drawer.getByLabel('W 当季度目标（元）').fill('260000');
  await drawer.getByLabel('起提门槛（元）', { exact: true }).fill('0');
  await drawer.locator('.ant-tabs-tabpane-active').getByLabel('本次修改依据').fill('隔离数据库UI验收');
  const periodSaved = page.waitForResponse(r => r.url().endsWith('/sales-formulas/inputs/period') && r.request().method() === 'PUT');
  await drawer.getByRole('button', { name: '保存季度参数并计算' }).click();
  if ((await periodSaved).status() !== 200) throw Error('period save failed');
  await drawer.getByRole('tab', { name: '服务计提规则R' }).click();
  await drawer.getByLabel('是否计发提成', { exact: true }).click();
  await page.locator('.ant-select-item-option').filter({ hasText: /^计发$/ }).click();
  await drawer.getByLabel('规则依据').fill('隔离测试服务规则');
  const serviceSaved = page.waitForResponse(r => r.url().endsWith('/sales-formulas/service') && r.request().method() === 'PUT');
  await drawer.getByRole('button', { name: '保存销售服务规则' }).click();
  if ((await serviceSaved).status() !== 200) throw Error('service save failed');
  await drawer.getByRole('tab', { name: '自动中间变量' }).click();
  await drawer.getByText('AB 奖金（未结算取整）', { exact: true }).waitFor();
  const config = await (await page.request.get(inputUrl)).json();
  if (!(Number(config.trace.bonus) > 0)) throw Error(JSON.stringify(config.trace.calculation));
  await drawer.getByRole('tab', { name: '订单外部变量' }).click();
  await drawer.getByLabel('AM 退款金额（仅识别，不自动扣奖）').fill('10');
  await drawer.locator('.ant-tabs-tabpane-active').getByLabel('本次修改依据').fill('隔离退款识别验收');
  const orderSaved = page.waitForResponse(r => r.url().endsWith('/sales-formulas/inputs/order') && r.request().method() === 'PUT');
  await drawer.getByRole('button', { name: '保存订单变量并计算' }).click();
  if ((await orderSaved).status() !== 200) throw Error('order variables save failed');
  const changed = await (await page.request.get(inputUrl)).json();
  if (!changed.trace.is_refunded || changed.trace.bonus !== config.trace.bonus) throw Error('refund unexpectedly changed bonus');
  await drawer.getByRole('tab', { name: 'BD季度参数' }).click();
  await drawer.getByLabel('W 当季度目标（元）').waitFor();
  await page.screenshot({ path: 'docs/sales-formula-inputs.png' });
  await page.locator('.ant-drawer-close').click();
  await sales.getByRole('button', { name: '确认 / 修改', exact: true }).first().click();
  await page.getByRole('dialog').waitFor();
  if (await page.getByRole('dialog').getByLabel('确认提点（%，结合首购/续费）').inputValue() !== '') throw Error('automatic rate leaked into manual override form');
  await page.getByRole('button', { name: '取 消', exact: true }).click();
  await sales.evaluate(el => el.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: 'docs/sales-formula-table.png' });
  if (errors.length) throw Error(JSON.stringify(errors));
  console.log('PASS: 19 columns, sales-only gears, formula dialog, quarter/service/order saves, recalculation, refund identification, manual override form.');
  await browser.close();
})().catch(async e => { console.error(e); if (globalThis.qaPage) { console.log(await globalThis.qaPage.locator('.ant-drawer-body').innerText({timeout:1000}).catch(() => 'no drawer')); await globalThis.qaPage.screenshot({ path: 'docs/sales-formula-ui-debug.png' }); } process.exit(1); });
