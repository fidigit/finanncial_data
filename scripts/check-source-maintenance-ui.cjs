const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
(async()=>{
 const base='http://127.0.0.1:18081/';
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.getByLabel('账号',{exact:true}).fill('admin');
  await page.getByLabel('密码',{exact:true}).fill('Demo2026!');
  await page.getByRole('button',{name:/登录工作台/}).click();
  const entries=page.locator('.commission-data-card').first().locator('.sales-source-entries button');
  await entries.first().waitFor();
  const close=async()=>{await page.locator('.sales-source-modal-wrap .ant-modal-close').click();await page.locator('.sales-source-modal').waitFor({state:'hidden'});};
  await entries.filter({hasText:/^奖金汇总表$/}).click();
  const target=page.getByLabel('季度目标编辑器');
  await target.locator('.target-member-name').first().waitFor();
  const remove=target.locator('.target-member-delete').first();
  assert.equal(await remove.evaluate(e=>getComputedStyle(e).opacity),'0');
  await target.locator('.target-member-name').first().hover();
  await page.waitForFunction(()=>Number(getComputedStyle(document.querySelector('.target-member-delete')).opacity)>.95);
  await target.getByRole('button',{name:'新增BD目标人员'}).click();
  await page.getByPlaceholder('选择或输入BD姓名').fill('UI验收同事');
  const add=page.waitForResponse(r=>r.url().includes('/members')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'加入当前及后续季度',exact:true}).click();
  assert((await add).ok());
  await target.getByRole('spinbutton',{name:'UI验收同事直接营收目标'}).waitFor();
  const name=target.locator('.target-member-name').filter({hasText:'UI验收同事'});
  await name.hover();await name.getByRole('button').click();
  const deleted=page.waitForResponse(r=>r.url().includes('/members')&&r.request().method()==='DELETE');
  await page.getByRole('button',{name:'删除当前及后续目标',exact:true}).click();
  assert((await deleted).ok());
  await target.getByRole('spinbutton',{name:'UI验收同事直接营收目标'}).waitFor({state:'hidden'});
  await page.screenshot({path:'data/ui-qa-20261116/target-editor.png'});
  await close();
  await entries.filter({hasText:/^奖金方案$/}).click();
  const plan=page.getByLabel('年度奖金方案编辑器');
  await plan.locator('.ant-table-row').first().waitFor();
  assert.equal(await plan.getByText(/个订单服务未配置/).count(),0);
  for(const name of ['UI手动来源一','UI手动来源二']){
   await plan.getByRole('button',{name:'新增奖金来源',exact:true}).click();
   await plan.getByRole('textbox',{name:'新增奖金来源名称',exact:true}).last().fill(name);
  }
  const pending={'所购服务':'UI手动来源一'};
  const choice=plan.getByRole('combobox',{name:pending['所购服务']+'是否计入提成范围',exact:true});
  assert((await choice.locator('xpath=ancestor::td').innerText()).includes('请选择'));
  await choice.click();await page.locator('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option').filter({hasText:/^否$/}).click();
  const saved=page.waitForResponse(r=>r.url().includes('/plans/')&&r.request().method()==='PUT');
  await plan.getByRole('button',{name:'保存本年方案',exact:true}).click();
  const savedData=await (await saved).json();
  assert.equal(savedData.rows.find(r=>r['所购服务']===pending['所购服务'])['是否计入提成范围'],'否');
  assert(savedData.rows.some(r=>r['是否计入提成范围']==null),'Saving one choice must not change remaining blank values to no');
  await page.screenshot({path:'data/ui-qa-20261116/service-editor.png'});
  await close();
  await entries.filter({hasText:/^C 订单号$/}).click();
  const orders=page.getByLabel('后台订单数据');
  await orders.locator('.ant-table-row').first().waitFor();
  assert.equal(await orders.locator('.ant-table-row').count(),20);
  const first=await orders.locator('.ant-table-row').first().innerText();
  const nextPage=page.waitForResponse(r=>r.url().includes('/sources/orders?page=2'));
  await orders.locator('.ant-pagination-next button').click();
  await nextPage;
  await orders.locator('.ant-table-row').first().waitFor();
  assert.notEqual(await orders.locator('.ant-table-row').first().innerText(),first);
  await orders.getByPlaceholder('订单号、BD或所购服务').fill('屈敬东');
  const searched=page.waitForResponse(r=>r.url().includes('/sources/orders?page=1')&&r.url().includes('search='));
  await orders.getByPlaceholder('订单号、BD或所购服务').press('Enter');
  assert((await searched).ok());await orders.locator('.ant-table-row').first().waitFor();
  assert((await orders.locator('.ant-table-row').allInnerTexts()).every(t=>t.includes('屈敬东')));
  await page.screenshot({path:'data/ui-qa-20261116/orders.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: hover delete; add/delete member; manually added blank service remains blank after saving others; live order search/pagination; no page errors.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
